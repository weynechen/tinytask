// 获取字符对应的字体位图索引
static int get_char_index(char ch) {
    // 字符集：0-9, A-Z, a-z
    if (ch >= '0' && ch <= '9') {
        return ch - '0';  // 数字0-9 (索引0-9)
    } else if (ch >= 'A' && ch <= 'Z') {
        return ch - 'A' + 10;  // 大写字母A-Z (索引10-35)
    } else if (ch >= 'a' && ch <= 'z') {
        return ch - 'a' + 36;  // 小写字母a-z (索引36-61)
    }
    
    // 不支持的字符返回0（数字0）
    return 0;
}

// 绘制单个字符
void draw_char(int x, int y, char ch, uint32_t color) {
    int idx = get_char_index(ch);
    
    // 检查坐标是否在有效范围内
    if (x < 0 || y < 0 || x >= LCD_WIDTH || y >= LCD_HEIGHT) {
        return;
    }
    
    // 对于不支持的字符，使用默认索引
    if (idx < 0 || idx >= FONT_CHAR_COUNT) {
        idx = 0;  // 默认使用数字0作为替代
    }
    
    // 获取字符位图
    const uint8_t *bitmap = font_bitmap[idx];
    
    // 计算可绘制的范围（确保不超出屏幕）
    int max_width = (x + FONT_WIDTH > LCD_WIDTH) ? LCD_WIDTH - x : FONT_WIDTH;
    int max_height = (y + FONT_HEIGHT > LCD_HEIGHT) ? LCD_HEIGHT - y : FONT_HEIGHT;
    
    // 绘制字符
    for (int row = 0; row < max_height; row++) {
        // 每行有两个字节，组成16位
        uint16_t line = (bitmap[row * 2] << 8) | bitmap[row * 2 + 1];
        
        for (int col = 0; col < max_width; col++) {
            // 最高位先处理
            if (line & (0x8000 >> col)) {
                lcd_draw_pixel(x + col, y + row, color);
            }
        }
    }
}

// 绘制字符串
void draw_string(int x, int y, const char *str, uint32_t color) {
    int pos_x = x;
    
    while (*str !='\0') {
        draw_char(pos_x, y, *str, color);
        str++;
        pos_x += FONT_WIDTH/2+2;
    }
} 